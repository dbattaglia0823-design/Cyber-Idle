test("save normalization preserves valid target progress and sanitizes malformed crafting quantities",()=>{
 let state=createInitialState(1000);
 state.resources.scrap=40;
 state=startCraft(state,jacket,1000,3,true);
 state=processCrafting(state,state.activeCraft.startedAt+state.activeCraft.durationMs,1);
 const restored=normalizeSave(JSON.parse(JSON.stringify(state)));
 assert.equal(restored.activeCraft.targetQuantity,3);
 assert.equal(restored.activeCraft.completedQuantity,1);
 assert.equal(restored.activeCraft.reserveMaterials,true);
 assert.equal(reservedCraftMaterial(restored,"scrap"),20);
 const old=normalizeSave({...createInitialState(1000),activeCraft:{recipeId:jacket,startedAt:1000,durationMs:6500}});
 assert.equal(old.activeCraft.targetQuantity,undefined);
 assert.equal(old.activeCraft.reserveMaterials,false);
 const corrupt=normalizeSave({...state,activeCraft:{recipeId:jacket,startedAt:1000,durationMs:6500,targetQuantity:-4,completedQuantity:-30,reserveMaterials:"yes"}});
 assert.equal(corrupt.activeCraft.targetQuantity,undefined);
 assert.equal(corrupt.activeCraft.completedQuantity,0);
 assert.equal(corrupt.activeCraft.reserveMaterials,false);
 const done=normalizeSave({...state,activeCraft:{...state.activeCraft,targetQuantity:1,completedQuantity:1}});
 assert.equal(done.activeCraft,null);
});
test("smart presets only propose safe, unlocked, guaranteed-output work",()=>{
 const state=createInitialState(1000);
 assert.deepEqual(smartPresetCatalog.map(p=>p.id),["upgrades","medical","hacking"]);
 for(const preset of smartPresetCatalog){
  const plan=planPreset(state,preset.id);
  assert.ok(plan.requested.length>0);
  assert.ok(plan.title);
  assert.ok(plan.steps.length<=8);
  for(const step of plan.steps){
    const action=skillActions.find(a=>a.id===step.actionId);
    assert.ok(action);
    assert.ok(canStartSkillAction(state,action));
    assert.ok(Object.values(action.rewards).every(amount=>(amount??0)>=0));
    assert.ok(Number(action.rewards[step.targetId]??action.itemRewards?.[step.targetId]??0)>0);
    assert.ok(step.maxCycles>=1&&step.maxCycles<=2000);
  }
 }
});
