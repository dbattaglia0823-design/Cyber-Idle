test("ingredient reserves prevent background skill work from spending future craft inputs",()=>{
 let state=createInitialState(1000);
 const action=getSkillAction(strip);
 state.resources.scrap=6;state.resources.cyberwareParts=3;
 assert.ok(canStartSkillAction(state,action));
 state=startCraft(state,med,1000,3,true);
 assert.equal(reservedCraftMaterial(state,"scrap"),6);
 assert.equal(reservedCraftMaterial(state,"cyberwareParts"),3);
 assert.equal(canStartSkillAction(state,action),false);
 assert.ok(state.activeCraft);
 const first=processCrafting(state,state.activeCraft.startedAt+state.activeCraft.durationMs);
 assert.equal(first.inventory["basic-med-injector"],1);
 assert.equal(first.activeCraft.completedQuantity,1);
 assert.equal(reservedCraftMaterial(first,"scrap"),4);
 assert.equal(canStartSkillAction(first,action),false);
 const free={...first, activeCraft:{...first.activeCraft,reserveMaterials:false}};
 assert.equal(canStartSkillAction(free,action),true,"disabling protection frees the remaining scrap for the skill");
 const rich={...state,resources:{...state.resources,scrap:9}};
 assert.equal(reservedCraftMaterial(rich,"scrap"),6);
 assert.equal(canStartSkillAction(rich,action),true);
});
