test("installing a reviewed preset replaces configuration without starting or mutating prior state",()=>{
 const original=addIdleQueueStep(createInitialState(1000),"scav-alley-scrap-run","scrap",12,3);
 const plan=planPreset(original,"upgrades");
 assert.ok(plan.steps.length>=1);
 const old=JSON.stringify(original);
 const replaced=installSupplyPlan(original,plan);
 assert.notEqual(replaced,original);
 assert.equal(replaced.idleQueue.enabled,false);
 assert.deepEqual(replaced.idleQueue.steps.map(x=>x.actionId),plan.steps.map(x=>x.actionId));
 assert.match(replaced.idleQueue.message,/prepared/);
 assert.equal(JSON.stringify(original),old);
 const running=startIdleQueue(original,1000);
 assert.equal(installSupplyPlan(running,plan),running);
 const invalid={...plan,steps:[{actionId:"invalid",targetId:"scrap",targetAmount:1,maxCycles:10,yieldPerCycle:1}]};
 assert.equal(installSupplyPlan(original,invalid),original);
});
