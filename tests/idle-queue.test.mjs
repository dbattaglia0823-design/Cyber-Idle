test("manual foreground switching pauses the queue, but does not stop background crafting",()=>{
 let state=twoStepQueue();
 state.resources.scrap=20;
 state=startIdleQueue(state,1000);
 state=startCraft(state,"recipe-scrap-jacket",1100);
 assert.equal(state.activeAction.actionId,"scav-alley-scrap-run");
 assert.equal(state.activeCraft.recipeId,"recipe-scrap-jacket");
 assert.equal(state.idleQueue.enabled,true);
 const originalCraft=state.activeCraft;
 const manual=startSkillAction(state,"hack-public-terminal",1200);
 assert.equal(manual.idleQueue.enabled,false);
 assert.equal(manual.activeAction.actionId,"hack-public-terminal");
 assert.deepEqual(manual.activeCraft,originalCraft);
 assert.deepEqual(stopSkillAction(manual).activeCraft,originalCraft);
 assert.equal(stopCraft(manual).activeAction.actionId,"hack-public-terminal");
 const enemy=allEnemies().find(e=>canFightEnemy(manual,e));
 assert.ok(enemy);
 const fighter=startCombat(manual,enemy.id,1300);
 assert.equal(fighter.activeAction,null);
 assert.deepEqual(fighter.activeCraft,originalCraft);
 assert.equal(stopCombat(fighter).activeCraft.recipeId,"recipe-scrap-jacket");
});
