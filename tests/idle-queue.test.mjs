 assert.equal(serialized.idleQueue.enabled,true);
 assert.equal(serialized.idleQueue.index,0);
 assert.equal(serialized.idleQueue.steps[0].cycles,1);
 assert.deepEqual(normalizeSave(serialized).idleQueue,serialized.idleQueue);
 const corrupted={ enabled:true, steps:[{id:"q1",actionId:"hack-public-terminal",targetId:"scrap",targetAmount:Infinity,maxCycles:-1,cycles:Infinity},{id:"q2",actionId:"scav-alley-scrap-run",targetId:"scrap",targetAmount:NaN,maxCycles:Infinity,cycles:-10}],index:99999,heatLimit:-5,nextId:Infinity,message:"!x".repeat(300)};
