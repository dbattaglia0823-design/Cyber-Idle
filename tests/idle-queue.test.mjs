function completeCurrent(state) {
 const activity=state.activeAction;
 assert.ok(activity, "expected an active queued skill");
 return processActionCompletion(state, activity.startedAt+activity.durationMs, 1);
}
function twoStepQueue() {
 let state=createInitialState(1000);
 state=addIdleQueueStep(state,"scav-alley-scrap-run","scrap",12,6);
 state=addIdleQueueStep(state,"hack-public-terminal","encryptedData",4,6);
 return state;
}
test("ordered queue switches at absolute resource targets and finishes without runner XP",()=>{
 let state=startIdleQueue(twoStepQueue(),1000);
 assert.equal(state.idleQueue.enabled,true);
 assert.equal(state.activeAction.actionId,"scav-alley-scrap-run");
 const runnerLevel=state.rpg.level,runnerXp=state.rpg.xp;
 state=completeCurrent(state);
 assert.equal(state.resources.scrap>=6,true);
 assert.equal(state.idleQueue.index,0);
 assert.equal(state.idleQueue.steps[0].cycles,1);
 state=completeCurrent(state);
 assert.equal(state.idleQueue.index,1);
 assert.equal(state.activeAction.actionId,"hack-public-terminal");
 assert.equal(state.idleQueue.steps[0].cycles,2);
 state=completeCurrent(state);
 assert.equal(state.idleQueue.index,1);
 state=completeCurrent(state);
 assert.equal(state.idleQueue.enabled,false);
 assert.equal(state.activeAction,null);
 assert.match(state.idleQueue.message,/complete/i);
 assert.ok(state.resources.encryptedData>=4);
 assert.equal(state.rpg.level,runnerLevel);
 assert.equal(state.rpg.xp,runnerXp);
});
test("absolute targets already held are skipped, empty queue does nothing, and pause leaves action working",()=>{
 const fresh=createInitialState(1000);
 assert.equal(startIdleQueue(fresh,1000),fresh);
 fresh.resources.scrap=100;
 let queue=twoStepQueue();queue.resources.scrap=100;
 queue=startIdleQueue(queue,1000);
 assert.equal(queue.idleQueue.index,1);
 assert.equal(queue.activeAction.actionId,"hack-public-terminal");
 const paused=pauseIdleQueue(queue);
 assert.equal(paused.idleQueue.enabled,false);
 assert.equal(paused.activeAction.actionId,queue.activeAction.actionId);
 const original=JSON.stringify(queue);
 const resumed=startIdleQueue(paused,paused.activeAction.startedAt+1000);
 assert.equal(resumed.idleQueue.enabled,true);
 assert.equal(resumed.idleQueue.index,1);
 assert.equal(JSON.stringify(queue),original);
});
test("queue limits, invalid targets and duplicate/oversized entries are rejected",()=>{
 let state=createInitialState(1000);
 assert.equal(addIdleQueueStep(state,"missing","scrap",50),state);
 assert.equal(addIdleQueueStep(state,"hack-public-terminal","scrap",5),state);
 assert.equal(addIdleQueueStep(state,"scav-alley-scrap-run","scrap",-1),state);
 assert.equal(addIdleQueueStep(state,"scav-alley-scrap-run","scrap",10,MAX_IDLE_QUEUE_RUNS+1),state);
 for(let i=0;i<MAX_IDLE_QUEUE_STEPS;i++)state=addIdleQueueStep(state,"scav-alley-scrap-run","scrap",(i+1)*10,100);
 assert.equal(state.idleQueue.steps.length,MAX_IDLE_QUEUE_STEPS);
 assert.equal(addIdleQueueStep(state,"scav-alley-scrap-run","scrap",1000),state);
 let moved=moveIdleQueueStep(state,state.idleQueue.steps[1].id,-1);
 assert.equal(moved.idleQueue.steps[0].targetAmount,20);
 const removed=removeIdleQueueStep(moved,moved.idleQueue.steps[0].id);
 assert.equal(removed.idleQueue.steps.length,MAX_IDLE_QUEUE_STEPS-1);
 assert.equal(resetIdleQueue(removed).idleQueue.index,0);
});
